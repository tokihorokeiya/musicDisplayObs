def get_text(lang, key, default=""):
    trans = TRANSLATIONS.get(lang, TRANSLATIONS.get("zh_TW", {}))
    return trans.get(key, default)

def get_theme_info(lang, theme_id):
    trans = TRANSLATIONS.get(lang, TRANSLATIONS.get("zh_TW", {}))
    theme_dict = trans.get("themes", {})
    if theme_id in theme_dict:
        return theme_dict[theme_id]
    return TRANSLATIONS["zh_TW"]["themes"].get(theme_id, (theme_id, ""))
