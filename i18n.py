def get_text(lang, key, default=""):
    trans = TRANSLATIONS.get(lang, TRANSLATIONS.get("en", {}))
    val = trans.get(key)
    if val:
        return val
    return TRANSLATIONS.get("en", {}).get(key, default)

def get_theme_info(lang, theme_id):
    theme_dict = TRANSLATIONS.get(lang, TRANSLATIONS["zh_TW"]).get("themes", {})
    if theme_id in theme_dict:
        return theme_dict[theme_id]
    return TRANSLATIONS["zh_TW"]["themes"].get(theme_id, (theme_id, ""))
